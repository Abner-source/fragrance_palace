import { createContext, useContext, useEffect, useState } from "react";
import { indexCatalogue } from "./catalogue.js";

/*
  The full catalogue (public/data/catalogue.json, generated by
  `npm run catalogue`) is fetched once and shared by every page.
*/

const CatalogueContext = createContext(null);
let cache = null;

export function CatalogueProvider({ children }) {
  const [state, setState] = useState(() => (cache ? { data: cache } : { loading: true }));

  useEffect(() => {
    if (cache) return;
    let alive = true;
    fetch(`${import.meta.env.BASE_URL}data/catalogue.json`)
      .then((r) => {
        if (!r.ok) throw new Error(`HTTP ${r.status}`);
        return r.json();
      })
      .then((json) => {
        cache = indexCatalogue(json);
        if (alive) setState({ data: cache });
      })
      .catch((error) => alive && setState({ error }));
    return () => { alive = false; };
  }, []);

  return <CatalogueContext.Provider value={state}>{children}</CatalogueContext.Provider>;
}

export const useCatalogue = () => useContext(CatalogueContext);
